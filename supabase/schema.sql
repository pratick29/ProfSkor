create extension if not exists pgcrypto;

create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  overall_score numeric not null check (overall_score >= 0 and overall_score <= 100),
  github_score numeric not null check (github_score >= 0 and github_score <= 100),
  leetcode_score numeric not null check (leetcode_score >= 0 and leetcode_score <= 100),
  linkedin_score numeric not null check (linkedin_score >= 0 and linkedin_score <= 100),
  created_at timestamptz not null default now()
);

create table if not exists public.saved_profiles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  profile_type text not null check (profile_type in ('github', 'leetcode', 'linkedin', 'fullscore', 'resume')),
  profile_name text not null,
  profile_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.user_preferences (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  preferences jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.resume_reviews (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  filename text not null,
  analysis_data jsonb not null default '{}'::jsonb,
  score numeric not null check (score >= 0 and score <= 100),
  created_at timestamptz not null default now()
);

create table if not exists public.subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  plan text not null default 'free' check (plan in ('free', 'pro', 'team')),
  status text not null default 'active' check (status in ('active', 'paused', 'cancelled', 'expired')),
  features jsonb not null default '{"resume_ai": true, "advanced_analytics": false, "admin": false}'::jsonb,
  current_period_end timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_scores_user_id_created_at on public.scores(user_id, created_at desc);
create index if not exists idx_saved_profiles_user_id_created_at on public.saved_profiles(user_id, created_at desc);
create index if not exists idx_resume_reviews_user_id_created_at on public.resume_reviews(user_id, created_at desc);
create index if not exists idx_audit_logs_user_id_created_at on public.audit_logs(user_id, created_at desc);

alter table public.scores enable row level security;
alter table public.saved_profiles enable row level security;
alter table public.user_preferences enable row level security;
alter table public.resume_reviews enable row level security;
alter table public.subscriptions enable row level security;
alter table public.audit_logs enable row level security;

drop policy if exists "scores_owner_policy" on public.scores;
create policy "scores_owner_policy" on public.scores
for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "profiles_owner_policy" on public.saved_profiles;
create policy "profiles_owner_policy" on public.saved_profiles
for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "preferences_owner_policy" on public.user_preferences;
create policy "preferences_owner_policy" on public.user_preferences
for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "resume_owner_policy" on public.resume_reviews;
create policy "resume_owner_policy" on public.resume_reviews
for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "subscriptions_owner_policy" on public.subscriptions;
create policy "subscriptions_owner_policy" on public.subscriptions
for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "audit_owner_policy" on public.audit_logs;
create policy "audit_owner_policy" on public.audit_logs
for select using (auth.uid() = user_id);
